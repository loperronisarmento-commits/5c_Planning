-- Vagas por unidade e turno: preenchidas, parciais e vazias
SELECT p.unidade, p.turno, COUNT(*) AS vagas,
       SUM(e.soma >= 0.999) AS completas, SUM(e.soma > 0 AND e.soma < 0.999) AS parciais, SUM(e.soma IS NULL) AS vazias
  FROM (SELECT id, unidade, turno FROM esc_posto WHERE versao = 'MODELO_27OUT') p
  CROSS JOIN (SELECT 'DONO' AS vaga UNION ALL SELECT 'COBERTURA') v
  LEFT JOIN (SELECT posto_id, vaga, SUM(fatia) AS soma FROM esc_vaga_equipe WHERE origem = 'CARGA_27OUT' GROUP BY posto_id, vaga) e
         ON e.posto_id = p.id AND e.vaga = v.vaga
 GROUP BY p.unidade, p.turno ORDER BY p.unidade, p.turno;
