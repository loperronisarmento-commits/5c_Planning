-- ES_211 · Dia de Overlap fixo por SR (5C Escalas 1.36.0, 23/11, pedido do usuário: "Sim, fixar"); via mysql.exe
--   Até aqui o dia de Overlap saía da ordem do código dentro do núcleo (posição i mod n da lista v4_overlap_posicao_ciclo):
--   quem entrava ou saía do núcleo mudava o Overlap de outros (ex.: Giovanna Melo, 23/11: 11 SRs do U2 A n1 e do U3 A n1).
--   Tabela nova esc_sr_overlap: a posição do ciclo (7 = segunda, 16 = quarta, 17 = quinta) de cada SR, que não muda mais.
--   Carga: a posição de hoje de cada SR, calculada como o motor calculou o plano 167 (pessoas vigentes em 06/12, ordem do
--   código no núcleo, lista 7,17,7,16,17), para nada mudar agora. Quem entrar depois recebe no Gerar a posição menos usada
--   no núcleo dele, e ela fica gravada. Par de Folga juntos continua com o mesmo Overlap do par (calculado na hora).
-- =====================================================================
