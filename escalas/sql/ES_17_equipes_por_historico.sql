SELECT 'linhas de equipe vigentes' AS item, COUNT(*) AS n, '418' AS esperado FROM esc_vaga_equipe e JOIN esc_posto p ON p.id = e.posto_id WHERE p.vigente_ate IS NULL AND e.vigente_ate IS NULL
UNION ALL SELECT 'linhas que não mudaram', COUNT(*), '132' FROM esc_vaga_equipe e JOIN tmp_es17_vaga t ON t.posto_id = e.posto_id AND t.vaga = e.vaga AND t.rep_code = e.rep_code WHERE e.vigente_ate IS NULL AND e.criado_em < NOW() - INTERVAL 1 MINUTE
UNION ALL SELECT 'SRs em equipe', COUNT(DISTINCT e.rep_code), '238' FROM esc_vaga_equipe e JOIN esc_posto p ON p.id = e.posto_id WHERE p.vigente_ate IS NULL AND e.vigente_ate IS NULL
UNION ALL SELECT 'postos sem núcleo dono', COUNT(*), '0' FROM esc_posto WHERE vigente_ate IS NULL AND nucleo_dono_id IS NULL;

-- SRs numa equipe com página em que trabalharam nas últimas 8 semanas (5C Schedule)
SELECT COUNT(DISTINCT e.rep_code) AS srs_em_equipe,
       COUNT(DISTINCT IF(s.codigo IS NULL, NULL, e.rep_code)) AS srs_que_conhecem_a_pagina, '161' AS esperado
  FROM esc_vaga_equipe e
  JOIN esc_posto p ON p.id = e.posto_id AND p.vigente_ate IS NULL
  JOIN esc_posto_pagina pp ON pp.posto_id = e.posto_id
  LEFT JOIN `5c_schedule`.scheduleday s ON s.codigo COLLATE utf8mb4_unicode_ci = e.rep_code AND s.modeloNome COLLATE utf8mb4_unicode_ci = pp.pagina
        AND s.shiftDateAndHour >= CONCAT(DATE_SUB(CURDATE(), INTERVAL 57 DAY), 'T00:00:00')
 WHERE e.vigente_ate IS NULL;

